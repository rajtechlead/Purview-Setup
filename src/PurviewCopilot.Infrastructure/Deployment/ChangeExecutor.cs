using System.Text;
using System.Text.Json;
using PurviewCopilot.Application.Abstractions;
using PurviewCopilot.Domain;

namespace PurviewCopilot.Infrastructure.Deployment;

/// <summary>
/// Executes change plans. Simulation is always available and produces the exact PowerShell that
/// would run. Live execution is disabled unless explicitly enabled by the host, because tenant
/// mutation must be a deliberate, approved action.
/// </summary>
public sealed class ChangeExecutor : IChangeExecutor
{
    private readonly bool _allowLiveExecution;

    public ChangeExecutor(bool allowLiveExecution = false) => _allowLiveExecution = allowLiveExecution;

    public Task<ExecutionResult> SimulateAsync(ChangePlan plan, CancellationToken cancellationToken = default)
    {
        var log = new List<string> { $"Plan {plan.Id} contains {plan.Operations.Count} operation(s)." };
        var automated = 0;
        var manual = 0;

        foreach (var operation in plan.Operations)
        {
            var script = PurviewScriptLibrary.Resolve(operation);

            log.Add($"VALIDATE {operation.Action} {operation.Target}");

            if (script.Automation == ScriptAutomation.Automated)
            {
                automated++;
                log.Add($"PRE-CHECK {operation.Id}: {script.Verification}");
            }
            else
            {
                manual++;
                log.Add($"MANUAL {operation.Id}: no supported cmdlet is mapped; complete {PurviewScriptLibrary.ControlId(operation)} in the Purview portal.");
            }

            if (string.IsNullOrWhiteSpace(operation.PayloadJson))
            {
                log.Add($"ERROR {operation.Id}: empty payload — operation would fail pre-deployment validation.");
                return Task.FromResult(new ExecutionResult(false, "Simulation failed validation.", log));
            }
        }

        if (plan.SimulationRequired)
        {
            log.Add("Simulation is mandatory for this plan; approval must reference the simulation report.");
        }

        log.AddRange(plan.Impact.ValidationSteps.Select(step => $"POST-CHECK {step}"));
        log.Add($"Dry run only. No tenant change was made. {automated} automated and {manual} manual operation(s).");

        return Task.FromResult(new ExecutionResult(true,
            $"Simulation completed: {automated} automated, {manual} manual. Review the generated script before applying.",
            log));
    }

    public Task<ExecutionResult> ApplyAsync(ChangePlan plan, CancellationToken cancellationToken = default)
    {
        if (!_allowLiveExecution)
        {
            return Task.FromResult(new ExecutionResult(false,
                "Live execution is disabled in this build. Enable it with an approved executor profile and certificate authentication.",
                new[] { "BLOCKED Live execution disabled by configuration." }));
        }

        var script = GenerateScript(plan);
        var log = new List<string>
        {
            $"Prepared script for {plan.Operations.Count} operation(s).",
            "Connect with certificate authentication and execute within the approved change window."
        };

        return Task.FromResult(new ExecutionResult(true,
            "Change script prepared. Execution must be run by the operator with the generated script.",
            log.Append(script).ToList()));
    }

    public Task<ExecutionResult> RollbackAsync(ConfigurationBackup backup, CancellationToken cancellationToken = default)
    {
        using var document = JsonDocument.Parse(backup.PayloadJson);
        var operations = document.RootElement.TryGetProperty("operations", out var ops) && ops.ValueKind == JsonValueKind.Array
            ? ops.GetArrayLength()
            : 0;

        return Task.FromResult(new ExecutionResult(true,
            $"Rollback package {backup.Label} validated ({operations} operation(s) to reverse).",
            new[]
            {
                "Restore labels and policies from the backup payload.",
                "Republish prior label policy version.",
                "Re-run assessment and confirm the previous scores are restored."
            }));
    }

    public string GenerateScript(ChangePlan plan) => BuildScript(plan);

    public string GenerateRollbackScript(ChangePlan plan) => BuildRollbackScript(plan);

    public static string BuildScript(ChangePlan plan)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Generated by Purview Governance Copilot — review before execution.");
        builder.AppendLine($"# Plan: {plan.Title}");
        builder.AppendLine($"# Plan ID: {plan.Id} | Tenant: {plan.TenantId} | Created: {plan.CreatedUtc:u}");
        builder.AppendLine("# Requires: ExchangeOnlineManagement; Connect-IPPSSession with certificate authentication.");
        builder.AppendLine("# Every block is idempotent: it checks current state before creating anything.");
        builder.AppendLine("$ErrorActionPreference = 'Stop'");
        builder.AppendLine("Import-Module ExchangeOnlineManagement");
        builder.AppendLine("Connect-IPPSSession -AppId $env:PGC_APP_ID -CertificateThumbprint $env:PGC_THUMBPRINT -Organization $env:PGC_ORG");
        builder.AppendLine();

        foreach (var operation in plan.Operations)
        {
            var script = PurviewScriptLibrary.Resolve(operation);
            builder.AppendLine($"# ---- {operation.Id}: {operation.Action} {operation.Target} [{script.Automation}]");
            builder.AppendLine($"# Pre-check: {script.Verification}");
            builder.AppendLine(script.Script);
            builder.AppendLine();
        }

        builder.AppendLine("Disconnect-ExchangeOnline -Confirm:$false");
        return builder.ToString();
    }

    /// <summary>
    /// Reversal script in reverse operation order. Removals are emitted as comments on purpose:
    /// rollback is a reviewed, approved action, never something to pipe straight into a shell.
    /// </summary>
    public static string BuildRollbackScript(ChangePlan plan)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Generated by Purview Governance Copilot — ROLLBACK SCRIPT (review before execution).");
        builder.AppendLine($"# Plan: {plan.Title}");
        builder.AppendLine($"# Plan ID: {plan.Id} | Tenant: {plan.TenantId}");
        builder.AppendLine("# Source of truth: the pre-change backup captured when this plan was created.");
        builder.AppendLine("# Destructive commands are commented out. Uncomment one at a time inside the approved window.");
        builder.AppendLine("# If any step fails, stop and restore the backup package instead of continuing.");
        builder.AppendLine("$ErrorActionPreference = 'Stop'");
        builder.AppendLine("Import-Module ExchangeOnlineManagement");
        builder.AppendLine("Connect-IPPSSession -AppId $env:PGC_APP_ID -CertificateThumbprint $env:PGC_THUMBPRINT -Organization $env:PGC_ORG");
        builder.AppendLine();

        foreach (var operation in plan.Operations.Reverse())
        {
            var control = PurviewScriptLibrary.ControlId(operation);
            var managed = PurviewScriptLibrary.ManagedObject(control);

            builder.AppendLine($"# ---- Reverse {operation.Id}: {operation.Action} {operation.Target}");
            builder.AppendLine($"# Verify current state first: {PurviewScriptLibrary.Verification(operation.Module)}");

            if (control == "AUD-01")
            {
                builder.AppendLine("# Set-AdminAuditLogConfig -UnifiedAuditLogIngestionEnabled $false  # DANGEROUS: disabling audit is not an approved rollback.");
                builder.AppendLine("# Instead, record the accepted exception and restore the previous audit configuration from the backup.");
            }
            else if (managed is not null)
            {
                builder.AppendLine($"# Object(s): {managed}");
                builder.AppendLine($"# Remove created object only after confirming it did not exist before this change:");
                builder.AppendLine($"# Remove-{RemovalVerb(control)} -Identity \"{managed.Split(',')[0].Trim()}\" -Force");
            }
            else
            {
                builder.AppendLine("# No automated reversal is mapped for this control; restore it from the backup and verify in the portal.");
            }

            builder.AppendLine();
        }

        builder.AppendLine("Disconnect-ExchangeOnline -Confirm:$false");
        return builder.ToString();
    }

    private static string RemovalVerb(string control) => control switch
    {
        "IPT-01" or "SEN-01" => "Label",
        "IPT-02" or "SEN-02" => "LabelPolicy",
        "AUT-01" or "AUT-02" => "AutoSensitivityLabelPolicy",
        "DLP-01" or "DLP-02" or "DLP-04" => "DlpCompliancePolicy",
        "REC-01" => "ComplianceTag",
        "DLM-01" or "DLM-02" => "RetentionCompliancePolicy",
        "AUD-02" => "UnifiedAuditLogRetentionPolicy",
        _ => "CompliancePolicy"
    };
}
