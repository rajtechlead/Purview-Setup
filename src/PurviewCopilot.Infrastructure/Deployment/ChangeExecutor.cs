using System.Text;
using System.Text.Json;
using PurviewCopilot.Application.Abstractions;
using PurviewCopilot.Domain;

namespace PurviewCopilot.Infrastructure.Deployment;

/// <summary>
/// Executes change plans. Simulation is always available and produces the exact PowerShell that
/// would run. Live execution is disabled unless explicitly enabled by the host, because tenant
/// mutation must be a deliberate, approved action.
/// </summary>
public sealed class ChangeExecutor : IChangeExecutor
{
    private readonly bool _allowLiveExecution;

    public ChangeExecutor(bool allowLiveExecution = false) => _allowLiveExecution = allowLiveExecution;

    public Task<ExecutionResult> SimulateAsync(ChangePlan plan, CancellationToken cancellationToken = default)
    {
        var log = new List<string> { $"Plan {plan.Id} contains {plan.Operations.Count} operation(s)." };

        foreach (var operation in plan.Operations)
        {
            log.Add($"VALIDATE {operation.Action} {operation.Target}");
            if (string.IsNullOrWhiteSpace(operation.PayloadJson))
            {
                log.Add($"ERROR {operation.Id}: empty payload — operation would fail pre-deployment validation.");
                return Task.FromResult(new ExecutionResult(false, "Simulation failed validation.", log));
            }
        }

        if (plan.SimulationRequired)
        {
            log.Add("Simulation is mandatory for this plan; approval must reference the simulation report.");
        }

        log.AddRange(plan.Impact.ValidationSteps.Select(step => $"POST-CHECK {step}"));
        log.Add("Dry run only. No tenant change was made.");

        return Task.FromResult(new ExecutionResult(true, "Simulation completed. Review the generated script before applying.", log));
    }

    public Task<ExecutionResult> ApplyAsync(ChangePlan plan, CancellationToken cancellationToken = default)
    {
        if (!_allowLiveExecution)
        {
            return Task.FromResult(new ExecutionResult(false,
                "Live execution is disabled in this build. Enable it with an approved executor profile and certificate authentication.",
                new[] { "BLOCKED Live execution disabled by configuration." }));
        }

        var script = BuildScript(plan);
        var log = new List<string>
        {
            $"Prepared script for {plan.Operations.Count} operation(s).",
            "Connect with certificate authentication and execute within the approved change window."
        };

        return Task.FromResult(new ExecutionResult(true,
            "Change script prepared. Execution must be run by the operator with the generated script.",
            log.Append(script).ToList()));
    }

    public Task<ExecutionResult> RollbackAsync(ConfigurationBackup backup, CancellationToken cancellationToken = default)
    {
        using var document = JsonDocument.Parse(backup.PayloadJson);
        var operations = document.RootElement.TryGetProperty("operations", out var ops) && ops.ValueKind == JsonValueKind.Array
            ? ops.GetArrayLength()
            : 0;

        return Task.FromResult(new ExecutionResult(true,
            $"Rollback package {backup.Label} validated ({operations} operation(s) to reverse).",
            new[]
            {
                "Restore labels and policies from the backup payload.",
                "Republish prior label policy version.",
                "Re-run assessment and confirm the previous scores are restored."
            }));
    }

    public static string BuildScript(ChangePlan plan)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Generated by Purview Governance Copilot — review before execution.");
        builder.AppendLine($"# Plan: {plan.Title}");
        builder.AppendLine("# Requires: ExchangeOnlineManagement; Connect-IPPSSession with certificate authentication.");
        builder.AppendLine("$ErrorActionPreference = 'Stop'");
        builder.AppendLine("Import-Module ExchangeOnlineManagement");
        builder.AppendLine("Connect-IPPSSession -AppId $env:PGC_APP_ID -CertificateThumbprint $env:PGC_THUMBPRINT -Organization $env:PGC_ORG");
        builder.AppendLine();

        foreach (var operation in plan.Operations)
        {
            builder.AppendLine($"# {operation.Id}: {operation.Action} {operation.Target}");
            builder.AppendLine($"Write-Host 'Applying {operation.Id} — {operation.Target}'");
            builder.AppendLine($"# Payload: {operation.PayloadJson}");
        }

        builder.AppendLine();
        builder.AppendLine("Disconnect-ExchangeOnline -Confirm:$false");
        return builder.ToString();
    }
}

