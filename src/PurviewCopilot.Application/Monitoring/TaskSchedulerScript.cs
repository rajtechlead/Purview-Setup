using System.Globalization;
using System.IO;

namespace PurviewCopilot.Application.Monitoring;

public sealed record TaskScheduleOptions(
    string CliPath,
    string TenantId,
    string ClientId,
    string Thumbprint,
    string DataDirectory,
    string ReportDirectory,
    string RunAt = "06:00",
    string TaskName = "Purview Governance Copilot daily assessment");

/// <summary>
/// Generates a self-contained PowerShell script. Run it once with -Register to create a daily
/// Windows Task Scheduler job; the job then invokes the same script without -Register, which runs
/// the headless CLI assessment and writes a timestamped report.
/// </summary>
public static class TaskSchedulerScript
{
    public static string Build(TaskScheduleOptions options)
    {
        if (!TimeOnly.TryParseExact(options.RunAt, "HH:mm", CultureInfo.InvariantCulture, DateTimeStyles.None, out var runAt))
        {
            throw new ArgumentException("Run time must be HH:mm, for example 06:00.");
        }

        if (string.IsNullOrWhiteSpace(options.CliPath))
        {
            throw new ArgumentException("The pgc executable path is required.");
        }

        if (string.IsNullOrWhiteSpace(options.TenantId) || string.IsNullOrWhiteSpace(options.ClientId) ||
            string.IsNullOrWhiteSpace(options.Thumbprint))
        {
            throw new ArgumentException("Tenant id, client id and certificate thumbprint are required for an unattended run.");
        }

        if (string.IsNullOrWhiteSpace(options.TaskName))
        {
            throw new ArgumentException("A task name is required.");
        }

        var time = runAt.ToString("HH:mm", CultureInfo.InvariantCulture);

        return $$"""
            param([switch]$Register)

            $ErrorActionPreference = 'Stop'
            $pgc = '{{Escape(options.CliPath)}}'
            $dataDir = '{{Escape(options.DataDirectory)}}'
            $reportDir = '{{Escape(options.ReportDirectory)}}'

            if ($Register) {
                $scriptPath = $MyInvocation.MyCommand.Path
                $action = New-ScheduledTaskAction -Execute 'powershell.exe' `
                    -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$scriptPath`""
                $trigger = New-ScheduledTaskTrigger -Daily -At '{{time}}'
                $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -DontStopOnIdleEnd
                Register-ScheduledTask -TaskName '{{Escape(options.TaskName)}}' `
                    -Action $action -Trigger $trigger -Settings $settings `
                    -Description 'Read-only Purview assessment generated by Purview Governance Copilot' `
                    -RunLevel Highest -Force | Out-Null

                Write-Host "Registered task '{{Escape(options.TaskName)}}' at {{time}} daily."
                exit 0
            }

            New-Item -ItemType Directory -Path $reportDir -Force | Out-Null
            $stamp = Get-Date -Format 'yyyyMMdd-HHmm'
            $report = Join-Path $reportDir "purview-$stamp.html"

            & $pgc assess `
                --tenant '{{Escape(options.TenantId)}}' `
                --client '{{Escape(options.ClientId)}}' `
                --thumbprint '{{Escape(options.Thumbprint)}}' `
                --data-dir $dataDir `
                --format html `
                --out $report `
                --by $env:USERNAME

            if ($LASTEXITCODE -ne 0) {
                Write-Error "Assessment failed with exit code $LASTEXITCODE."
                exit $LASTEXITCODE
            }

            Write-Host "Assessment written to $report."
            exit 0
            """;
    }

    private static string Escape(string value) => value.Replace("'", "''");
}
